//! macOS virtual key codes to key names, by table lookup. Resolving the typed character instead
//! would call `TSMGetInputSourceProperty`, which must run on the main thread.

/// Reference: HIToolbox `Events.h`.
pub fn keycode_to_name(keycode: u16) -> String {
    match keycode {
        0x00 => "a".into(),
        0x01 => "s".into(),
        0x02 => "d".into(),
        0x03 => "f".into(),
        0x04 => "h".into(),
        0x05 => "g".into(),
        0x06 => "z".into(),
        0x07 => "x".into(),
        0x08 => "c".into(),
        0x09 => "v".into(),
        0x0B => "b".into(),
        0x0C => "q".into(),
        0x0D => "w".into(),
        0x0E => "e".into(),
        0x0F => "r".into(),
        0x10 => "y".into(),
        0x11 => "t".into(),
        0x12 => "1".into(),
        0x13 => "2".into(),
        0x14 => "3".into(),
        0x15 => "4".into(),
        0x16 => "6".into(),
        0x17 => "5".into(),
        0x18 => "=".into(),
        0x19 => "9".into(),
        0x1A => "7".into(),
        0x1B => "-".into(),
        0x1C => "8".into(),
        0x1D => "0".into(),
        0x1E => "]".into(),
        0x1F => "o".into(),
        0x20 => "u".into(),
        0x21 => "[".into(),
        0x22 => "i".into(),
        0x23 => "p".into(),
        0x24 => "Return".into(),
        0x25 => "l".into(),
        0x26 => "j".into(),
        0x27 => "'".into(),
        0x28 => "k".into(),
        0x29 => ";".into(),
        0x2A => "\\".into(),
        0x2B => ",".into(),
        0x2C => "/".into(),
        0x2D => "n".into(),
        0x2E => "m".into(),
        0x2F => ".".into(),
        0x30 => "Tab".into(),
        0x31 => "Space".into(),
        0x32 => "`".into(),
        0x33 => "Backspace".into(),
        0x35 => "Escape".into(),
        0x37 => "MetaLeft".into(), // Command
        0x38 => "ShiftLeft".into(),
        0x39 => "CapsLock".into(),
        0x3A => "Alt".into(), // Option
        0x3B => "ControlLeft".into(),
        0x3C => "ShiftRight".into(),
        0x3D => "AltGr".into(), // Right Option
        0x3E => "ControlRight".into(),
        0x3F => "Function".into(),
        0x60 => "F5".into(),
        0x61 => "F6".into(),
        0x62 => "F7".into(),
        0x63 => "F3".into(),
        0x64 => "F8".into(),
        0x65 => "F9".into(),
        0x67 => "F11".into(),
        0x69 => "F13".into(),
        0x6B => "F14".into(),
        0x6D => "F10".into(),
        0x6F => "F12".into(),
        0x71 => "F15".into(),
        0x72 => "Help".into(),
        0x73 => "Home".into(),
        0x74 => "PageUp".into(),
        0x75 => "Delete".into(),
        0x76 => "F4".into(),
        0x77 => "End".into(),
        0x78 => "F2".into(),
        0x79 => "PageDown".into(),
        0x7A => "F1".into(),
        0x7B => "Left".into(),
        0x7C => "Right".into(),
        0x7D => "Down".into(),
        0x7E => "Up".into(),
        // Numpad keys
        0x41 => "KpDelete".into(),
        0x43 => "KpMultiply".into(),
        0x45 => "KpPlus".into(),
        0x47 => "NumLock".into(),
        0x4B => "KpDivide".into(),
        0x4C => "KpReturn".into(),
        0x4E => "KpMinus".into(),
        0x51 => "Kp=".into(),
        0x52 => "Kp0".into(),
        0x53 => "Kp1".into(),
        0x54 => "Kp2".into(),
        0x55 => "Kp3".into(),
        0x56 => "Kp4".into(),
        0x57 => "Kp5".into(),
        0x58 => "Kp6".into(),
        0x59 => "Kp7".into(),
        0x5B => "Kp8".into(),
        0x5C => "Kp9".into(),
        _ => format!("Unknown(0x{:02X})", keycode),
    }
}
